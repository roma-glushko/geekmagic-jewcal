//! `gen-tz`: build `model/src/tz_table.rs` from the TZif footers of the
//! system tz database. Each TZif v2+ file ends with `\n<POSIX TZ string>\n`,
//! which describes the zone's current rules.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const ZONEINFO: &str = "/usr/share/zoneinfo";
const OUT: &str = "model/src/tz_table.rs";

pub fn run() -> super::Res {
    let mut zones: BTreeMap<String, String> = BTreeMap::new();
    walk(Path::new(ZONEINFO), "", &mut zones)?;
    if zones.is_empty() {
        return Err(format!("no TZif files under {ZONEINFO}").into());
    }
    let version = fs::read_to_string(Path::new(ZONEINFO).join("+VERSION")).unwrap_or_else(|_| "unknown".into());

    let mut posix: Vec<&str> = zones.values().map(String::as_str).collect();
    posix.sort_unstable();
    posix.dedup();

    let mut src = String::new();
    writeln!(src, "// @generated by `cargo run -p jewcal-sim -- gen-tz` from {ZONEINFO} (tzdata {}).", version.trim())?;
    writeln!(src, "// IANA zone name -> POSIX TZ rule (the TZif footer). Do not edit by hand.\n")?;
    writeln!(src, "pub(crate) static POSIX: &[&str] = &[")?;
    for p in &posix {
        writeln!(src, "    {p:?},")?;
    }
    writeln!(src, "];\n")?;
    writeln!(src, "/// Sorted by name for binary search.")?;
    writeln!(src, "pub(crate) static ZONES: &[(&str, u16)] = &[")?;
    for (name, p) in &zones {
        let idx = posix.binary_search(&p.as_str()).expect("deduped above");
        writeln!(src, "    ({name:?}, {idx}),")?;
    }
    writeln!(src, "];")?;
    fs::write(OUT, src)?;
    println!("wrote {OUT}: {} zones, {} distinct rules (tzdata {})", zones.len(), posix.len(), version.trim());
    Ok(())
}

fn walk(dir: &Path, prefix: &str, out: &mut BTreeMap<String, String>) -> super::Res {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        // `posix/` and `right/` duplicate the tree; the rest are not zones.
        if prefix.is_empty() && matches!(name.as_str(), "posix" | "right" | "posixrules" | "localtime" | "Factory") {
            continue;
        }
        let full = if prefix.is_empty() { name.clone() } else { format!("{prefix}/{name}") };
        let path = entry.path();
        if path.is_dir() {
            walk(&path, &full, out)?;
        } else if let Some(footer) = footer(&fs::read(&path)?) {
            out.insert(full, footer);
        }
    }
    Ok(())
}

fn footer(bytes: &[u8]) -> Option<String> {
    if bytes.len() < 44 || &bytes[..4] != b"TZif" || bytes[4] < b'2' {
        return None;
    }
    let body = bytes.strip_suffix(b"\n")?;
    let start = body.iter().rposition(|&b| b == b'\n')? + 1;
    let s = std::str::from_utf8(&body[start..]).ok()?;
    (!s.is_empty() && s.is_ascii()).then(|| s.to_string())
}
